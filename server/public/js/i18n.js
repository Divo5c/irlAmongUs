export function langActive() {
  return browserStorage.getItem('rlaus_lang') === 'en' ? 'en' : 'de';
}

export function localText(de, en) {
  return langActive() === 'en' ? en : de;
}

export function t(key, values = {}) {
  const lang = langActive();
  const phrase = TEXT[key]?.[lang === 'en' ? 1 : 0] ?? key;
  return phrase.replace(/\{(\w+)\}/g, (match, field) => Object.hasOwn(values, field) ? values[field] : match);
}

export function roomErrorText(code) {
  const pair = Object.hasOwn(ROOM_ERRORS, code) ? ROOM_ERRORS[code] : null;
  return pair ? localText(...pair) : null;
}

